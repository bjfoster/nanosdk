"""Render the nanosdk half of a generated client: parameter models, routes, clients."""

from __future__ import annotations

import re
from collections import defaultdict
from typing import Any

from ._openapi import Api, Operation, Param, pascal

MARKERS = {
    "path": "Path",
    "query": "Query",
    "header": "Header",
    "body": "Body",
    "form": "Form",
    "file": "File",
}


def render_client(api: Api, *, name: str, base_url: str, spec_name: str) -> str:
    """The source of `client.py` for `api` (unformatted; ruff formats it)."""
    params = {op.name: _params_model(op) for op in api.operations if _needs_params_model(op)}
    groups: dict[str, list[Operation]] = defaultdict(list)
    for op in api.operations:
        groups[op.tag].append(op)

    lines = [
        f'"""{api.title} {api.version}: routes and clients generated by nanosdk from {spec_name}.',
        "",
        "Don't edit this file: regenerate it with `nanosdk generate`. To customise the",
        "client, subclass it (and override routes or hooks) in a module of your own.",
        '"""',
        "",
        f"# Generated by nanosdk from {spec_name}; don't edit by hand.",
        "",
        "import logging",
        "from collections.abc import Mapping",
    ]
    used = _referenced(api)
    params_source = "\n".join(params.values())
    dates = sorted(n for n in ("date", "datetime") if n in used)
    if dates:
        lines.append(f"from datetime import {', '.join(dates)}")
    typing_names = {"Any"} | {n for n in ("Annotated", "Literal") if n in params_source}
    pydantic_names = [
        *(["BaseModel"] if params else []),
        *(["Field"] if "Field(" in params_source else []),
    ]
    lines += [
        f"from typing import {', '.join(sorted(typing_names))}",
        "",
        "import httpx",
        *([f"from pydantic import {', '.join(pydantic_names)}"] if pydantic_names else []),
        "",
        "import nanosdk",
        "from nanosdk.client import DEFAULT_TIMEOUT, TimeoutTypes",
        "",
    ]
    models = sorted(api.model_names & used)
    if models:
        lines.append(f"from .models import {', '.join(models)}")
    lines += ["", f"DEFAULT_BASE_URL = {base_url!r}", '"""The first server in the spec."""', ""]

    if params:
        lines += ["", "# --- parameters " + "-" * 70, ""]
        for source in params.values():
            lines += ["", source, ""]

    group_names: list[str] = []
    lines += ["", "# --- routes " + "-" * 74, ""]
    for tag, ops in groups.items():
        cls = f"{pascal(tag)}Routes"
        group_names.append(cls)
        doc = api.tags.get(tag) or f"Operations tagged {tag!r}."
        lines += ["", f"class {cls}(nanosdk.Routes):", f"    {_doc(doc)}", ""]
        for op in ops:
            lines += [f"    {_route(op, params)}", f"    {_doc(_route_doc(op))}", ""]

    lines += ["", "# --- clients " + "-" * 73, ""]
    for asynchronous in (False, True):
        lines += ["", _client(api, name, group_names, asynchronous=asynchronous)]
    return "\n".join(lines) + "\n"


def render_init(api: Api, *, name: str, spec_name: str) -> str:
    """The source of the generated package's `__init__.py`."""
    return (
        f'"""{api.title} {api.version} client, generated by nanosdk from {spec_name}.\n\n'
        "Don't edit: regenerate with `nanosdk generate`.\n"
        '"""\n\n'
        "from . import models\n"
        f"from .client import DEFAULT_BASE_URL, Async{name}, {name}\n\n"
        f'__all__ = ["DEFAULT_BASE_URL", "Async{name}", "{name}", "models"]\n'
    )


# --- pieces -------------------------------------------------------------------------------


def _referenced(api: Api) -> set[str]:
    """Identifiers the emitted code uses (skipped operations' models aren't imported)."""
    exprs = [api.error_model or ""]
    for op in api.operations:
        exprs += [op.request_model or "", op.response or "", *(p.type for p in op.params)]
    return {name for expr in exprs for name in re.findall(r"[A-Za-z_]\w*", expr)}


def _needs_params_model(op: Operation) -> bool:
    return op.request_model is None and bool(op.params)


def _params_class(op: Operation) -> str:
    return f"{pascal(op.name)}Params"


def _params_model(op: Operation) -> str:
    lines = [
        f"class {_params_class(op)}(BaseModel):",
        f"    {_doc(f'Parameters of `{op.name}`: {op.method.upper()} {op.path}.')}",
        "",
    ]
    for p in op.params:
        lines.append(f"    {p.name}: {_annotation(p)}{'' if p.required else ' = None'}")
    return "\n".join(lines)


def _annotation(p: Param) -> str:
    marker_args = ""
    if p.location in ("header", "form", "file") or (p.location == "query" and p.wire != p.name):
        marker_args = f"alias={p.wire!r}"  # headers always: nanosdk would dash underscores
    marker = f"nanosdk.{MARKERS[p.location]}({marker_args})"
    constraints = ", ".join(f"{k}={v!r}" for k, v in p.constraints.items())
    description = f"description={p.description!r}" if p.description else ""
    if p.required:
        # One Annotated: constraints and description share a Field.
        field_args = ", ".join(a for a in (constraints, description) if a)
        extras = [*([f"Field({field_args})"] if field_args else []), marker]
        return f"Annotated[{p.type}, {', '.join(extras)}]"
    # Optional: constraints must apply to the inner type, not to `X | None`.
    base = f"Annotated[{p.type}, Field({constraints})]" if constraints else p.type
    if not base.endswith("| None"):
        base = f"{base} | None"
    extras = [marker, *([f"Field({description})"] if description else [])]
    return f"Annotated[{base}, {', '.join(extras)}]"


def _route(op: Operation, params: dict[str, str]) -> str:
    args = [repr(op.path)]
    if op.request_model is not None:
        args.append(f"request={op.request_model}")
    elif op.name in params:
        args.append(f"request={_params_class(op)}")
    if op.response is not None:
        args.append(f"response={op.response}")
    args.append("exclude_unset=True")
    args.append(f"meta={{'operation_id': {op.operation_id!r}}}")
    return f"{op.name} = nanosdk.{op.method}({', '.join(args)})"


def _route_doc(op: Operation) -> str:
    summary = (op.summary or f"{op.method.upper()} {op.path}").rstrip(".")
    return f"{summary}." + (" Deprecated." if op.deprecated else "")


def _client(api: Api, name: str, groups: list[str], *, asynchronous: bool) -> str:
    cls = f"Async{name}" if asynchronous else name
    base = "nanosdk.AsyncClient" if asynchronous else "nanosdk.Client"
    http = "httpx.AsyncClient" if asynchronous else "httpx.Client"
    error_default = api.error_model or "None"
    summary = (
        f"{'Asynchronous' if asynchronous else 'Synchronous'} client for {api.title} {api.version}."
    )
    doc = [
        summary,
        "",
        "Takes the same arguments as `nanosdk."
        + ("AsyncClient" if asynchronous else "Client")
        + "`; `base_url` defaults to",
        "`DEFAULT_BASE_URL`"
        + (f" and `error_model` to `{api.error_model}`." if api.error_model else "."),
    ]
    bases = ", ".join([*groups, base])
    return f'''class {cls}({bases}):
    """{chr(10).join(("    " + line) if line else "" for line in doc).lstrip()}
    """

    def __init__(
        self,
        base_url: str | httpx.URL | None = None,
        *,
        headers: Mapping[str, str] | None = None,
        timeout: TimeoutTypes = DEFAULT_TIMEOUT,
        auth: httpx.Auth | tuple[str, str] | None = None,
        error_model: type[Any] | None = {error_default},
        retry: nanosdk.Retry | None = None,
        logger: logging.Logger | None = None,
        http_client: {http} | None = None,
        **httpx_kwargs: Any,
    ) -> None:
        if base_url is None:
            base_url = "" if http_client is not None else DEFAULT_BASE_URL
        super().__init__(
            base_url,
            headers=headers,
            timeout=timeout,
            auth=auth,
            error_model=error_model,
            retry=retry,
            logger=logger,
            http_client=http_client,
            **httpx_kwargs,
        )
'''


def _doc(text: Any) -> str:
    cleaned = " ".join(str(text).split()).replace('"""', "'''").replace("\\", "\\\\")
    return f'"""{cleaned}"""'
